import {readFileSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {renderAgentOperations} from './agent-skill-reference.ts';

// Only reviewed generic instructions are eligible for anonymous distribution.
// Never glob the Skill directory: installations may have private local files.
export function renderSkillArtifactSource() {
  const files = {
    'LICENSE': readFileSync(new URL('../LICENSE',import.meta.url),'utf8'),
    'SKILL.md': readFileSync(new URL('../skills/lifeos-agent/SKILL.md',import.meta.url),'utf8'),
    'references/credential-runtime.md': readFileSync(new URL('../skills/lifeos-agent/references/credential-runtime.md',import.meta.url),'utf8'),
    'references/operations.md': renderAgentOperations(),
  };
  return '// Generated by scripts/agent-skill-artifact.ts from the reviewed public allowlist.\n' +
    'export const skillArtifactFiles = ' + JSON.stringify(files,null,2) + ' as const;\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(new URL('../src/agent-api/skill-artifact-content.generated.ts',import.meta.url),renderSkillArtifactSource());
}
